
from database.connection import DatabaseConnection


def createTables():
    try:
        db_config = DatabaseConnection()
        cursor = db_config.cursor()

        # 1. Users Table
        users_table_query = """
        CREATE TABLE IF NOT EXISTS users (
            userid BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            username VARCHAR(50) NOT NULL,
            email VARCHAR(50) NOT NULL UNIQUE,
            hashpassword VARCHAR(255) NOT NULL,
            role VARCHAR(20) DEFAULT 'admin'
                CHECK (role IN ('admin', 'user')),
            gender VARCHAR(10)
                CHECK (gender IN ('male', 'female')),
            phone VARCHAR(15),
            dateofbirth DATE,
            profilename VARCHAR(255),
            profilepath VARCHAR(255),
            is_active BOOLEAN DEFAULT TRUE,
            created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
            updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
        );
        """

        # 2. Products Table
        products_table_query = """
        CREATE TABLE IF NOT EXISTS products (
            productid BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            productname VARCHAR(100) NOT NULL,
            description TEXT,
            category VARCHAR(50),
            quantity INTEGER DEFAULT 0 CHECK (quantity >= 0),
            buyprice NUMERIC(15,2) DEFAULT 0.0,
            saleprice NUMERIC(15,2) DEFAULT 0.0,
            imgname VARCHAR(100),
            storedpath VARCHAR(255),
            is_active BOOLEAN DEFAULT TRUE,
            created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
            updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
        );
        """

        # 3. Orders Table
        orders_table_query = orders_table_query = """
            CREATE TABLE IF NOT EXISTS orders (
            orderid BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            userid BIGINT,
            status VARCHAR(20) DEFAULT 'pending'
            CHECK (status IN ('shipped', 'delivered', 'cancelled', 'pending')),
            address VARCHAR(255),
            total NUMERIC(20,2) DEFAULT 0.00,
            created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
            FOREIGN KEY (userid) REFERENCES users(userid));
        """

        # 4. Order Details Table
        orderdetails_table_query = """
        CREATE TABLE IF NOT EXISTS order_details (
            orderid BIGINT,
            productid BIGINT,
            quantity INTEGER DEFAULT 1 CHECK (quantity >= 0),
            price NUMERIC(15,2) DEFAULT 0.0,
            subtotal NUMERIC(20,2)
                GENERATED ALWAYS AS (quantity * price) STORED,
            FOREIGN KEY (orderid) REFERENCES orders(orderid),
            FOREIGN KEY (productid) REFERENCES products(productid)
        );
        """

        # 5. Payments Table
        payments_table_query = """CREATE TABLE IF NOT EXISTS payments (
            paymentid BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            userid BIGINT,
            orderid BIGINT,
            status VARCHAR(100) DEFAULT 'pending',
            method VARCHAR(20)
            CHECK (method IN ('cash', 'upi', 'netbanking', 'razorpay')),
            amount NUMERIC(20,2) DEFAULT 0.0,
            razorpay_order_id VARCHAR(255),
            razorpay_payment_id VARCHAR(255),
            created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
            FOREIGN KEY (userid) REFERENCES users(userid),
            FOREIGN KEY (orderid) REFERENCES orders(orderid));
        """



        # 6. Cart Table
        cart_table_query = """
        CREATE TABLE IF NOT EXISTS cart (
            cartid BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            userid BIGINT,
            productid BIGINT,
            quantity INTEGER DEFAULT 1,
            FOREIGN KEY (userid) REFERENCES users(userid),
            FOREIGN KEY (productid) REFERENCES products(productid)
        );
        """

        tables = [
            users_table_query,
            products_table_query,
            orders_table_query,
            orderdetails_table_query,
            payments_table_query,
            cart_table_query
        ]

        for table_query in tables:
            cursor.execute(table_query)

        db_config.commit()

        cursor.close()
        db_config.close()

        return "Tables Created Successfully"

    except Exception as e:
        if 'db_config' in locals():
            db_config.rollback()
            db_config.close()

        return f"Something wrong in database/tables.py: {e}"
